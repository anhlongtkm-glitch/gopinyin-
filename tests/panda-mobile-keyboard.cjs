'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('playwright-core');
const {register} = require('./helpers/supabase-fixture.cjs');
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  const context = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2});
  const page = await context.newPage(), errors=[];
  page.setDefaultTimeout(12000);
  const evidence=path.resolve('.cache/panda-mobile-layout');
  fs.mkdirSync(evidence,{recursive:true});
  const observations=[];
  async function measure(label) {
    const result=await page.evaluate(()=>{
      const rect=selector=>{const r=document.querySelector(selector).getBoundingClientRect();return {top:r.top,bottom:r.bottom,height:r.height,left:r.left,right:r.right};};
      const controls=['gaKbdBtn','gaPyBtn','gaPauseBtn'].map(id=>{
        const element=document.getElementById(id),r=element.getBoundingClientRect();
        const hit=document.elementFromPoint(r.x+r.width/2,r.y+r.height/2);
        return {id,top:r.top,bottom:r.bottom,width:r.width,height:r.height,hit:hit===element||element.contains(hit)};
      });
      return {width:innerWidth,height:innerHeight,scrollWidth:document.documentElement.scrollWidth,stage:rect('#gaStage'),keyboard:rect('#vkbd'),card:rect('#gameCard'),controls};
    });
    observations.push({label,...result});
    await page.screenshot({path:path.join(evidence,label+'.png')});
    return result;
  }
  page.on('pageerror',e=>errors.push(e.message));
  try {
    await page.goto(process.env.TEST_URL || 'http://localhost:8080/');
    await register(page,'Touch pilot');
    await page.evaluate(()=>{localStorage.removeItem('gp:vk');window.showView('game');});
    await page.locator('#gaStartBtn').waitFor({state:'visible'});
    await page.tap('#gaStartBtn');
    await page.waitForFunction(()=>window.__game._state.running);
    await page.locator('#vkbd').waitFor({state:'visible'});
    await page.waitForFunction(()=>document.querySelector('#gaPlayer').getBoundingClientRect().bottom<=document.querySelector('#vkbd').getBoundingClientRect().top);
    const target=await page.evaluate(()=>window.__game._state.items.find(i=>!i.caught).src.pyPlain);
    await page.tap('#vkbd [data-vk="'+target[0]+'"]');
    assert.equal(await page.evaluate(()=>window.__game._state.buffer),target[0]);
    console.log('  PASS touch devices automatically show a working keyboard when the countdown finishes');
    await page.tap('#vkbd [data-vk="hide"]');
    assert(await page.locator('#vkbd').isHidden());
    await page.tap('#gaKbdBtn');
    assert(await page.locator('#vkbd').isVisible());
    assert.equal(await page.locator('#gaKbdBtn').getAttribute('aria-pressed'),'true');
    console.log('  PASS touch Hide and keyboard toggle close and reopen without a double toggle');
    // A real user gesture is required for fullscreen; do not mock document.fullscreenElement.
    await page.evaluate(()=>{
      const button=document.createElement('button'); button.id='testFullscreen'; button.textContent='Fullscreen';
      button.style.cssText='position:fixed;top:0;right:0;z-index:99999';
      button.onclick=()=>document.querySelector('#gameCard').requestFullscreen();document.body.append(button);
    });
    await page.tap('#testFullscreen');
    await page.waitForFunction(()=>document.fullscreenElement?.id==='gameCard');
    await page.waitForFunction(()=>document.querySelector('#vkbd').parentElement===document.fullscreenElement);
    assert.equal(await page.evaluate(()=>document.querySelector('#vkbd').parentElement.id),'gameCard');
    await page.tap('#vkbd [data-vk="'+target[1]+'"]');
    assert.equal(await page.evaluate(()=>window.__game._state.buffer),target.slice(0,2));
    await page.evaluate(()=>document.exitFullscreen());
    await page.waitForFunction(()=>!document.fullscreenElement);
    await page.waitForFunction(()=>document.querySelector('#vkbd').parentElement===document.body);
    assert.equal(await page.evaluate(()=>document.querySelector('#vkbd').parentElement.tagName),'BODY');
    await page.evaluate(()=>document.querySelector('#testFullscreen').remove());
    console.log('  PASS keyboard remains visible and accepts touch input inside and after real fullscreen');
    await page.setViewportSize({width:390,height:740});
    await page.waitForTimeout(300);
    const bounds = await page.evaluate(()=>({ship:document.querySelector('#gaPlayer').getBoundingClientRect().bottom,keyboard:document.querySelector('#vkbd').getBoundingClientRect().top,scroll:document.documentElement.scrollWidth,width:innerWidth}));
    assert(bounds.ship<=bounds.keyboard,JSON.stringify(bounds)); assert(bounds.scroll<=bounds.width+1);
    fs.mkdirSync(path.resolve('.cache/panda-game'),{recursive:true});
    await page.screenshot({path:path.resolve('.cache/panda-game/mobile-touch.png')});
    await page.evaluate(()=>window.showView('games'));
    await page.locator('#vkbd').waitFor({state:'hidden'});
    assert.equal(await page.evaluate(()=>localStorage.getItem('gp:vk')),'1');
    assert.deepEqual(errors,[]);
    console.log('  PASS shorter mobile layout avoids overlap; leaving game hides keyboard without forgetting its preference');
    await page.evaluate(()=>window.showView('game'));
    await page.tap('[data-pd="resume-flight"]');
    await page.locator('#vkbd').waitFor({state:'visible'});
    for(const size of [{width:320,height:568},{width:360,height:640},{width:390,height:844},{width:412,height:915}]) {
      await page.setViewportSize(size);
      await page.waitForTimeout(200);
      const bounds=await measure(size.width+'x'+size.height+'-playing');
      assert(bounds.stage.height>=112,JSON.stringify(bounds));
      assert(bounds.stage.bottom<=bounds.keyboard.top,JSON.stringify(bounds));
      assert(bounds.card.bottom<=bounds.keyboard.top,JSON.stringify(bounds));
      assert(bounds.controls.every(control=>control.hit&&control.top>=0&&control.bottom<=bounds.keyboard.top),JSON.stringify(bounds));
      assert(bounds.scrollWidth<=bounds.width);
    }
    console.log('  PASS 320, 360, 390 and 412px mobile layouts keep the stage and flight controls above the keyboard with real hit targets');
    await page.setViewportSize({width:844,height:390});
    await page.locator('#pdViewportNotice').waitFor({state:'visible'});
    assert.equal(await page.evaluate(()=>window.__game._state.paused),true);
    const saved=await page.evaluate(()=>{const g=window.__game._state;return {score:g.score,buffer:g.buffer,elapsed:g.elapsed,lives:g.lives};});
    await page.waitForTimeout(500);
    assert.deepEqual(await page.evaluate(()=>{const g=window.__game._state;return {score:g.score,buffer:g.buffer,elapsed:g.elapsed,lives:g.lives};}),saved);
    await page.screenshot({path:path.join(evidence,'844x390-paused-notice.png')});
    const exit=await page.locator('[data-viewport-leave]').evaluate(e=>{const r=e.getBoundingClientRect(),hit=document.elementFromPoint(r.x+r.width/2,r.y+r.height/2);return r.top>=0&&r.bottom<=innerHeight&&(hit===e||e.contains(hit));});
    assert(exit);
    console.log('  PASS insufficient landscape space pauses time and lives, preserves input and exposes an unobscured exit');
    await page.setViewportSize({width:320,height:568});
    await page.locator('#pdViewportNotice').waitFor({state:'hidden'});
    assert.equal(await page.evaluate(()=>window.__game._state.paused),true);
    await page.locator('[data-pd="resume"]').scrollIntoViewIfNeeded();
    await page.tap('[data-pd="resume"]');
    assert.equal(await page.evaluate(()=>window.__game._state.paused),false);
    await page.tap('#vkbd [data-vk="hide"]');
    await page.tap('#gaKbdBtn');
    await page.waitForTimeout(200);
    const small=await measure('320x568-reopened');
    assert(small.controls.every(control=>control.hit));
    console.log('  PASS returning to portrait requires explicit resume and small-screen keyboard toggles remain tappable');
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(()=>{
      Object.defineProperty(visualViewport,'height',{configurable:true,value:600});
      Object.defineProperty(visualViewport,'offsetTop',{configurable:true,value:12});
      visualViewport.dispatchEvent(new Event('resize'));
      visualViewport.dispatchEvent(new Event('scroll'));
    });
    await page.waitForTimeout(200);
    const visual=await measure('390-visual-viewport-shrunk');
    assert.equal(visual.card.top,12);
    assert(visual.keyboard.bottom<=612.5,JSON.stringify(visual));
    assert(visual.card.bottom<=visual.keyboard.top,JSON.stringify(visual));
    await page.evaluate(()=>{delete visualViewport.height;delete visualViewport.offsetTop;visualViewport.dispatchEvent(new Event('resize'));});
    console.log('  PASS visual viewport resize and scroll update both card and keyboard while the layout viewport stays unchanged');
    await page.evaluate(()=>{
      const button=document.createElement('button');button.id='testFullscreen';button.textContent='Fullscreen';
      button.style.cssText='position:fixed;top:0;right:0;z-index:99999';
      button.onclick=()=>document.querySelector('#gameCard').requestFullscreen();document.body.append(button);
    });
    await page.tap('#testFullscreen');
    await page.waitForFunction(()=>document.fullscreenElement?.id==='gameCard');
    await page.setViewportSize({width:844,height:390});
    await page.locator('#pdViewportNotice').waitFor({state:'visible'});
    assert.equal(await page.evaluate(()=>document.querySelector('#pdViewportNotice').parentElement===document.fullscreenElement),true);
    await page.tap('[data-viewport-leave]');
    await page.locator('#gamesCard').waitFor({state:'visible'});
    await page.waitForFunction(()=>!document.fullscreenElement);
    await page.evaluate(()=>document.querySelector('#testFullscreen').remove());
    assert(await page.locator('#vkbd').isHidden());
    assert(await page.locator('#pdViewportNotice').isHidden());
    assert.deepEqual(errors,[]);
    console.log('  PASS fullscreen landscape notice remains interactive and exit closes fullscreen, notice and keyboard');
    await page.setViewportSize({width:320,height:568});
    await page.evaluate(()=>window.showView('game'));
    await page.tap('[data-pd="resume-flight"]');
    await page.locator('#vkbd').waitFor({state:'visible'});
    await page.tap('#gaPauseBtn');
    await page.locator('[data-pd="resume"]').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(evidence,'320x568-paused-panel.png')});
    await page.tap('[data-pd="resume"]');
    await page.tap('#vkbd [data-vk="hide"]');
    await page.tap('#gaOptionsBtn');
    await page.locator('[data-pd="close-options"]').scrollIntoViewIfNeeded();
    await page.tap('[data-pd="close-options"]');
    await page.tap('#gaKbdBtn');
    await page.evaluate(()=>window.__game._update(95));
    await page.locator('.pdPanel--result').waitFor({state:'visible'});
    await page.locator('[data-pd="topics"]').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(evidence,'320x568-results-panel.png')});
    await page.tap('[data-pd="topics"]');
    await page.locator('#gaStartBtn').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(evidence,'320x568-ready-panel.png')});
    await page.tap('#gaStartBtn');
    await page.waitForFunction(()=>window.__game._state.running);
    assert.deepEqual(errors,[]);
    await page.evaluate(()=>window.showView('games'));
    console.log('  PASS short-screen pause, settings, results, topic selection and countdown retain reachable actions');
    fs.writeFileSync(path.join(evidence,'observations.json'),JSON.stringify(observations,null,2));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
